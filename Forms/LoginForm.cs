        // One service for the lifetime of the form. AuthService keeps no state and holds no
        // open connection - every call inside it opens a connection, runs and closes again -
        // so a single field is safe here and saves constructing one on every click.
        // readonly says the reference is assigned once: no later method can swap the service
        // out from under the click handler.
        private readonly AuthService _auth = new AuthService();

        public LoginForm()
        {
            // InitializeComponent is generated by the designer and creates every control on
            // the form. Nothing else belongs in the constructor: the window does not exist
            // yet at this point, so anything that can fail - and in particular anything that
            // touches the database - is done in LoginForm_Load instead, where a failure can
            // be shown in a label rather than crashing before a window has appeared.
            InitializeComponent();
        }

